export function tr(lang: Lang, key: Key | string, params?: Record<string, string | number>): string {
  let s: string = (DICT[lang] as Record<string, string>)[key] ?? (DICT.de as Record<string, string>)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

// ---------------------------------------------------------------- Text-Bausteine der Engine

/**
 * Ein übersetzbarer Text aus der Engine (Zugbeschreibung, Spielverlauf).
 * Wird erst beim Anzeigen in die gewählte Sprache übersetzt – so wechselt auch der bisherige Verlauf die Sprache.
 *  - string:           fester Text (z. B. alte Spielstände)
 *  - { k, p }:         Wörterbuch-Schlüssel mit Parametern (die selbst Bausteine sein dürfen)
 *  - { pl }:           Name des Spielers auf Platz pl
 *  - { col } / { adj }: Farbname bzw. Adjektiv der Farbe
 *  - { card }:         Kartenname
 *  - { j, s }:         Liste, verbunden mit Trennzeichen s
 */
export type Phrase =
  | string
  | { k: Key; p?: Record<string, Phrase | number> }
  | { pl: number }
  | { col: number }
  | { adj: number }
  | { card: CardValue }
  | { j: Phrase[]; s?: string };

export const ph = (k: Key, p?: Record<string, Phrase | number>): Phrase => ({ k, p });

export function cardName(lang: Lang, v: CardValue | null): string {
  if (v === null) return "–";
  return typeof v === "number" ? String(v) : tr(lang, `card.${v}`);
}

export function say(phrase: Phrase, lang: Lang, names: string[]): string {
  if (typeof phrase === "string") return phrase;
  if ("pl" in phrase) return names[phrase.pl] ?? "?";
  if ("col" in phrase) return tr(lang, `color.${phrase.col}`);
  if ("adj" in phrase) return tr(lang, `adj.${phrase.adj}`);
  if ("card" in phrase) return cardName(lang, phrase.card);
  if ("j" in phrase) return phrase.j.map((x) => say(x, lang, names)).join(phrase.s ?? ", ");
  const params: Record<string, string | number> = {};
  for (const [k, v] of Object.entries(phrase.p ?? {})) params[k] = typeof v === "number" ? v : say(v, lang, names);
  return tr(lang, phrase.k, params);
}
